/**
 * Arena B: OpenRouter SDK façade backed by Cloudflare Workers AI for live mode.
 * Original UB-IAD/sd-ai source is downloaded at a pinned SHA and NEVER modified.
 * A fetch interceptor receives real SDK requests, forwards the JSON schema to
 * Cloudflare AI, and translates the REAL result back to OpenRouter's envelope.
 * Offline mode uses a clearly marked synthetic Cloudflare response.
 *
 * This tests: model slug dispatch -> original LLMWrapper/OpenRouter SDK ->
 * JSON-schema request -> original QuantitativeEngineBrain.processResponse.
 * It does NOT use OpenRouter's service, change Buffalo, or claim causal G3.
 */
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { pathToFileURL } from "node:url";
import { createHash } from "node:crypto";
import {CF_MODEL,OR_SLUG,CF_MODE,requestToCloudflare,responseToOpenRouter} from "./arena_b_cf_protocol_adapter.mjs";

const UPSTREAM_SHA="5199f7b45f3a7ae4a773cb0dd8542940aabe9edc";
const MODEL=OR_SLUG;
const OUT=resolve(process.env.BUFFALO_OUTPUT??"artifacts/buffalo-openrouter-cloudflare");
const ROOT=resolve(process.env.SDAI_ROOT??"upstream/sd-ai");
const INPUT=resolve(process.env.BUFFALO_VISIBLE_INPUT??"data/synthetic/arena_b_native_visible.json");
const SCENARIO=process.env.BUFFALO_CF_MODE??"offline";
const hash=v=>"sha256:"+createHash("sha256").update(typeof v==="string"?v:JSON.stringify(v)).digest("hex");
const receipt={schema:"igc-b-openrouter-cloudflare/0.1",model:MODEL,
  upstream_sha:UPSTREAM_SHA,scenario:SCENARIO,
  transport:CF_MODE,real_model:CF_MODEL,live_provider_calls:0,
  intercepted_http_calls:0,original_upstream_modified:false,model_returned:false,
  structured_request_seen:false,status:"INITIALIZED"};

const syntheticModel={
  specs:{startTime:0,stopTime:8,dt:0.1,timeUnits:"Hour",integrationMethod:"Euler"},
  variables:[
    {name:"Backlog",type:"stock",units:"items",inflows:[],outflows:[],
     equation:"0",uniflow:false,documentation:"Work still pending.",graphicalFunction:{points:[]}},
    {name:"Completed",type:"stock",units:"items",inflows:["Completions"],outflows:[],
     equation:"0",uniflow:false,documentation:"Cumulative work delivered.",graphicalFunction:{points:[]}},
    {name:"Arrivals",type:"flow",units:"items/hour",inflows:[],outflows:[],
     equation:"1.7",uniflow:true,documentation:"New work arrives.",graphicalFunction:{points:[]}},
    {name:"Completions",type:"flow",units:"items/hour",inflows:[],outflows:[],
     equation:"MIN(2, Backlog / 1)",uniflow:true,documentation:"Completed work per hour.",graphicalFunction:{points:[]}}
  ],
  relationships:[
    {from:"Arrivals",to:"Backlog",polarity:"+",reasoning:"Material addition",polarityReasoning:"Increasing arrivals increases pending work"},
    {from:"Completions",to:"Backlog",polarity:"-",reasoning:"Material depletion",polarityReasoning:"Completion reduces pending work"},
    {from:"Completions",to:"Completed",polarity:"+",reasoning:"Material addition",polarityReasoning:"Completion increases delivered work"}
  ],
  explanation:"OFFLINE TEST RESPONSE ONLY — not generated by a model.",
  title:"Offline Buffalo OpenRouter transport exercise"
};
const save=async(name,obj)=>writeFile(join(OUT,name),JSON.stringify(obj,null,2)+"\n");
await mkdir(OUT,{recursive:false});
const originals={fetch:globalThis.fetch};
try {
  if(!["offline","live"].includes(SCENARIO))throw Error("INVALID_SCENARIO");
  if(SCENARIO==="live" && (process.env.BUFFALO_CF_AUTH!=="RUN_SINGLE_CF_AI_MODEL" ||
     process.env.GITHUB_RUN_ATTEMPT!=="1"))throw Error("CLOUDFLARE_LIVE_NOT_AUTHORIZED");
  const visible=JSON.parse(await readFile(INPUT,"utf8"));
  if(visible.schema!=="igc-arena-visible-input/0.1")throw Error("BAD_VISIBLE_SCHEMA");
  if(Object.keys(visible.construction||{}).some(k=>/gold|holdout|other.arm/i.test(k)))throw Error("FORBIDDEN_INPUT");
  // Instrument the transport BEFORE dynamic-importing the original SDK.
  // All other fetch calls are blocked to prevent accidental real network access.
  globalThis.fetch=async function openRouterOfflineIntercept(request,init={}){
    receipt.intercepted_http_calls++;
    const url = new URL(typeof request==="string"?request:request.url);
    const method = init.method??(request instanceof Request?request.method:"GET");
    if(url.origin!=="https://openrouter.ai" ||
       !url.pathname.endsWith("/chat/completions") ||
       method.toUpperCase()!=="POST"){
      throw Error("UNEXPECTED_OUTBOUND_HTTP:"+url.origin+url.pathname);
    }
    if(receipt.intercepted_http_calls!==1)throw Error("MULTIPLE_OPENROUTER_REQUESTS");
    let content=init.body??(request instanceof Request?await request.text():null);
    if(typeof content!=="string")content=Buffer.isBuffer(content)?content.toString("utf8"):String(content??"");
    const body=JSON.parse(content);
    if(body.model!==MODEL)throw Error("WRONG_OPENROUTER_MODEL");
    const responseFormat=body.response_format??body.responseFormat;
    if(responseFormat?.type!=="json_schema")throw Error("ORIGINAL_OPENROUTER_SCHEMA_NOT_SENT");
    const schema=responseFormat.json_schema?.schema??responseFormat.jsonSchema?.schema;
    if(!schema?.properties?.variables || !schema?.properties?.relationships)
      throw Error("QUANTITATIVE_STRUCTURE_MISSING");
    receipt.structured_request_seen=true;
    receipt.request_sha256=hash(body);
    receipt.schema_sha256=hash(schema);
    receipt.message_role_sequence=body.messages?.map(m=>m.role);
    await save("intercepted-request-metadata.json",{
      http_method:method,url_origin:url.origin,url_path:url.pathname,
      model:body.model,response_format:responseFormat.type,
      request_sha256:receipt.request_sha256,schema_sha256:receipt.schema_sha256,
      prompt_hashes:body.messages.map(m=>({role:m.role,sha256:hash(m.content)})),
      upstream_source_modified:false
    });
    const cfBody=requestToCloudflare(body);
    receipt.cloudflare_schema_sha256=hash(cfBody.response_format.json_schema);
    receipt.translated_body_sha256=hash(cfBody);
    await save("cf-request-metadata.json",{
      actual_model:CF_MODEL,endpoint:"Workers AI /ai/run/{model}",
      translated_body_sha256:receipt.translated_body_sha256,
      schema_sha256:receipt.cloudflare_schema_sha256,
      parameter_overrides:{reasoning_effort:"low",max_completion_tokens:cfBody.max_completion_tokens},
      source_prompts_unchanged:true,openrouter_service_used:false
    });
    let cf;
    if(SCENARIO==="offline"){
      cf={success:true,result:{response:syntheticModel,
        usage:{prompt_tokens:0,completion_tokens:0,total_tokens:0}}};
      receipt.inference_source="SYNTHETIC_CLOUDFLARE_FIXTURE";
    } else {
      const account=process.env.CLOUDFLARE_ACCOUNT_ID;
      const token=process.env.CLOUDFLARE_API_TOKEN;
      if(!/^[a-fA-F0-9]{32}$/.test(account??"") || !token)
        throw Error("CLOUDFLARE_SECRETS_NOT_AVAILABLE");
      const endpoint="https://api.cloudflare.com/client/v4/accounts/"+account+"/ai/run/"+CF_MODEL;
      receipt.live_provider_calls++;
      receipt.inference_source="REAL_CLOUDFLARE_WORKERS_AI";
      await save("cf-call-started.json",{model:CF_MODEL,
        request_sha256:receipt.translated_body_sha256,
        calls_started:receipt.live_provider_calls,
        date:new Date().toISOString()});
      const response=await originals.fetch(endpoint,{
        method:"POST",headers:{"Authorization":"Bearer "+token,"Content-Type":"application/json"},
        body:JSON.stringify(cfBody),signal:AbortSignal.timeout(160000)
      });
      receipt.cf_http_status=response.status;
      const raw=await response.text();
      try{cf=JSON.parse(raw)}catch{
        await save("cf-nonjson-error.json",{http_status:response.status,
          body_sha256:hash(raw),size:raw.length});
        throw Error("CLOUDFLARE_NON_JSON_RESPONSE");
      }
      await save("cloudflare-raw.json",cf);
      receipt.raw_cloudflare_preserved=true;
      if(!response.ok)throw Error("CLOUDFLARE_HTTP_"+response.status);
    }
    const envelope=responseToOpenRouter(cf,receipt.request_sha256);
    receipt.generated_content_sha256=hash(envelope.choices[0].message.content);
    receipt.compatibility_envelope_synthesized=true;
    await save("openrouter-compat-envelope.json",envelope);
    return new Response(JSON.stringify(envelope),{status:200,headers:{"content-type":"application/json"}});
  };
  // The original OpenRouter SDK is loaded solely from original installed upstream.
  process.env.OPEN_ROUTER_API_KEY="IGC_LOCAL_ONLY_NOT_REAL_OPENROUTER_KEY";
  const {default:Engine}=await import(pathToFileURL(join(ROOT,"engines/quantitative/engine.js")).href);
  const engine=new Engine();
  const params={
    underlyingModel:MODEL,
    supportsArrays:false,supportsModules:false,supportsSubTypes:false,mentorMode:false,
    problemStatement:visible.question,
    backgroundKnowledge:JSON.stringify({construction:visible.construction,
      observability:visible.observability}),
    maxTokens:8000,timeoutMinutes:2
  };
  const result=await engine.generate(visible.question,{variables:[],relationships:[]},params);
  await save("native-output.json",result);
  receipt.model_returned=Array.isArray(result?.model?.variables)&&
                          Array.isArray(result?.model?.relationships);
  receipt.native_error=result?.err??null;
  receipt.variable_count=result?.model?.variables?.length??null;
  receipt.relationship_count=result?.model?.relationships?.length??null;
  receipt.buffalo_inferred_arrivals_as_inflow=
    result?.model?.variables?.find(v=>v.name==="Backlog")?.inflows?.includes("Arrivals")??false;
  receipt.status=receipt.model_returned?
    (SCENARIO==="live"?"REAL_CLOUDFLARE_NATIVE_BUFFALO_MODEL_RETURNED":"OFFLINE_CF_FAÇADE_NATIVE_ENGINE_PASS"):
    "BUFFALO_RETURNED_NO_NATIVE_MODEL";
} catch(e) {
  receipt.error_type=e?.name??"Error";
  receipt.error_message=String(e.message??e).slice(0,350);
  receipt.status="OPENROUTER_CF_BRIDGE_FAILURE";
} finally {
  globalThis.fetch=originals.fetch;
  await save("receipt.json",receipt);
  console.log(JSON.stringify(receipt));
  if(SCENARIO==="offline") {
    if(receipt.status!=="OFFLINE_CF_FAÇADE_NATIVE_ENGINE_PASS" ||
       !receipt.buffalo_inferred_arrivals_as_inflow ||
       !receipt.structured_request_seen || receipt.intercepted_http_calls!==1 ||
       receipt.live_provider_calls!==0)process.exitCode=1;
  } else if(!receipt.model_returned || receipt.live_provider_calls!==1) {
    process.exitCode=1;
  }
}
