"""Render a hash-pinned requirements file from pip's install report."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def normalized(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def render_lock(report_path: Path) -> str:
    report = json.loads(report_path.read_text(encoding="utf-8"))
    packages: dict[str, tuple[str, str, list[str]]] = {}
    for item in report.get("install", []):
        metadata = item["metadata"]
        name = normalized(metadata["name"])
        version = metadata["version"]
        hashes = item.get("download_info", {}).get("archive_info", {}).get("hashes", {})
        sha256 = hashes.get("sha256")
        if not sha256:
            raise ValueError(f"pip report has no sha256 for {name}=={version}")
        current = packages.get(name)
        if current and current[0] != version:
            raise ValueError(f"conflicting versions for {name}: {current[0]} and {version}")
        packages[name] = (version, item["download_info"]["url"], sorted(set((sha256,))))
    lines = [
        "# Generated by scripts/lock_from_pip_report.py from pip's install report.",
        "# Target: GitHub Actions ubuntu-24.04, CPython 3.13.16, x86_64.",
        "# Refresh intentionally; this file pins the resolved dependency closure.",
    ]
    for name, (version, _url, hashes) in sorted(packages.items()):
        lines.append(f"{name}=={version} \\")
        for index, digest in enumerate(hashes):
            suffix = " \\" if index < len(hashes) - 1 else ""
            lines.append(f"    --hash=sha256:{digest}{suffix}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("report", type=Path)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    lock_text = render_lock(args.report)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(lock_text, encoding="utf-8")
    print(lock_text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
