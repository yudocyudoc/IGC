#!/usr/bin/env python3
"""G5 tests use INVENTED configurations and temporary external directories.

They do NOT select a CAF-01 world, call a model, generate evidence or authorize
construction/evaluation. Random nonces generated by local toy tests are not
scientific seals.
"""
import copy
import json
import os
from pathlib import Path
import stat
import tempfile
import unittest

from caf01_des_engine import SCHEMA as DES_SCHEMA, TIE_POLICY
from caf01_g5_seal import (
    CONTRACT, G5Blocked, ROOT, SCHEMA, FILES_TO_PIN, canonical,
    hard_budget, make_public_receipt, seal_offline, sha_bytes,
    snapshot_files, verify_receipt,
)


def invented():
    return {"schema": DES_SCHEMA, "tie_policy": TIE_POLICY,
            "stages": [{"servers": 1, "service_minutes": "3/2"},
                       {"servers": 2, "service_minutes": "2"}]}


class TestCAF01G5OfflineSeal(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.contract = json.loads(CONTRACT.read_text(encoding="utf-8"))

    def receipt(self, config=None, nonce=b"\x05"*32):
        return make_public_receipt(
            invented() if config is None else config,
            nonce, pinned_files=snapshot_files(),
            budget=hard_budget(self.contract))

    def test_hard_original_budget_no_new_experimental_allowance(self):
        b=hard_budget(self.contract)
        self.assertEqual(b["binding_preparation_ceiling_original_v03"]["DES"]["total"],2)
        self.assertEqual(b["binding_preparation_ceiling_original_v03"]["RK4_D"]["total"],36)
        self.assertEqual(b["binding_preparation_ceiling_original_v03"]["OpenModelica"]["total"],26)
        self.assertEqual(b["binding_preparation_ceiling_original_v03"]["Buffalo"]["total"],2)
        self.assertEqual(b["conditional_not_yet_authorized_OM_reduction"]["total"],20)
        self.assertIn("NOT_EXECUTION_AUTHORIZED",b["status"])
        self.assertEqual(b["binding_preparation_ceiling_original_v03"]["automatic_retries"],0)

    def test_modified_or_nonzero_budget_fails_closed(self):
        c=copy.deepcopy(self.contract)
        c["budget"]["actual_DES_runs"]=1
        with self.assertRaisesRegex(G5Blocked,"G5_BUDGET_CHANGED_OR_ALREADY_CONSUMED"):
            hard_budget(c)
        c=copy.deepcopy(self.contract)
        c["budget"]["OpenModelica_candidate_runs"]["total_max"]=27
        with self.assertRaisesRegex(G5Blocked,"G5_BUDGET_CHANGED_OR_ALREADY_CONSUMED"):
            hard_budget(c)

    def test_public_receipt_hides_private_world_details_and_nonce(self):
        config=invented()
        r=self.receipt(config)
        blob=json.dumps(r)
        self.assertNotIn("service_minutes",blob)
        self.assertNotIn('"servers"',blob)
        self.assertNotIn("nonce_hex",blob)
        self.assertNotIn("stages",blob)
        self.assertFalse(r["private_parameters_in_receipt"])
        self.assertEqual(r["public_arrival_counts"],{"construction":24,"evaluation":30})
        self.assertEqual(r["sampling_minutes"],[0,5,10,15,20,30,40])
        self.assertFalse(r["future_evaluation_reveal_authorized"])
        self.assertEqual(r["external_custody"]["verification_status"],"NOT_VERIFIED")
        self.assertEqual(r["private_DES_world_runs"],0)
        self.assertEqual(r["receipt_content_sha256"],
                         sha_bytes(canonical({k:v for k,v in r.items()
                                              if k!="receipt_content_sha256"})))

    def test_private_commitment_is_salted_by_32_secret_bytes(self):
        r=self.receipt(nonce=b"\x05"*32)
        r2=self.receipt(nonce=b"\x07"*32)
        self.assertNotEqual(r["world_precommitment_sha256"],
                            r2["world_precommitment_sha256"])
        self.assertTrue(verify_receipt(invented(),b"\x05"*32,r,
                        pinned_files=snapshot_files(),
                        budget=hard_budget(self.contract))["execution_authorized"] is False)
        with self.assertRaisesRegex(G5Blocked,"PRECOMMITMENT_OR_SOURCE_CHANGED"):
            verify_receipt(invented(),b"\x07"*32,r,
                           pinned_files=snapshot_files(),
                           budget=hard_budget(self.contract))

    def test_config_changed_or_moved_tamper_blocks(self):
        r=self.receipt()
        mutated=invented()
        mutated["stages"][0]["service_minutes"]="4"
        with self.assertRaisesRegex(G5Blocked,"PRECOMMITMENT_OR_SOURCE_CHANGED"):
            verify_receipt(mutated,b"\x05"*32,r,
                           pinned_files=snapshot_files(),
                           budget=hard_budget(self.contract))
        altered=copy.deepcopy(r)
        altered["budget"]["binding_preparation_ceiling_original_v03"]["DES"]["total"]=3
        with self.assertRaisesRegex(G5Blocked,"PRECOMMITMENT_OR_SOURCE_CHANGED"):
            verify_receipt(invented(),b"\x05"*32,altered,
                           pinned_files=snapshot_files(),
                           budget=hard_budget(self.contract))

    def test_source_pins_change_blocks_verification(self):
        self.assertEqual(set(snapshot_files()),set(FILES_TO_PIN))
        original=snapshot_files()
        forged=dict(original)
        forged["caf01_des_engine.py"]="sha256:"+"0"*64
        r=self.receipt()
        with self.assertRaisesRegex(G5Blocked,"PRECOMMITMENT_OR_SOURCE_CHANGED"):
            verify_receipt(invented(),b"\x05"*32,r,
                           pinned_files=forged,
                           budget=hard_budget(self.contract))

    def test_nonempty_private_world_is_not_needed_in_tests_or_main(self):
        self.assertEqual(self.receipt()["schema"],SCHEMA)
        for bad in (
            {"schema":DES_SCHEMA,"tie_policy":TIE_POLICY,"stages":[]},
            {"schema":DES_SCHEMA,"tie_policy":"UNAPPROVED","stages":[{"servers":1,"service_minutes":"2"}]},
            {"schema":DES_SCHEMA,"tie_policy":TIE_POLICY,"stages":[{"servers":0,"service_minutes":"2"}]},
            {"schema":DES_SCHEMA,"tie_policy":TIE_POLICY,"stages":[{"servers":1,"service_minutes":"0"}]},
        ):
            with self.subTest(bad=bad),self.assertRaisesRegex(G5Blocked,"INVALID_PRIVATE_CONFIG"):
                self.receipt(config=bad)

    def test_short_nonce_refused(self):
        with self.assertRaisesRegex(G5Blocked,"NONCE_MUST_BE_32"):
            self.receipt(nonce=b"short")

    def test_seal_toy_outside_repo_separates_secret_and_public_bytes(self):
        with tempfile.TemporaryDirectory() as tmp:
            base=Path(tmp)
            cfg=base/"researcher-selection.json"
            cfg.write_text(json.dumps(invented()),encoding="utf-8")
            priv=base/"offline-vault"
            pub=base/"public-receipt.json"
            result=seal_offline(cfg,priv,pub,nonce=b"\x06"*32)
            self.assertEqual(result["state"],"PRECOMMITTED_LOCALLY_NOT_EXTERNALLY_CUSTODIED")
            self.assertFalse(result["construction_run_authorized"])
            self.assertFalse(result["evaluation_run_authorized"])
            self.assertFalse(result["private_config_in_output"])
            secret=json.loads((priv/"private-envelope.json").read_text())
            public=json.loads(pub.read_text())
            self.assertEqual(secret["config"],invented())
            self.assertEqual(secret["nonce_hex"],(b"\x06"*32).hex())
            self.assertNotIn("nonce_hex",public)
            self.assertNotIn("stages",json.dumps(public))
            self.assertNotIn("service_minutes",json.dumps(public))
            self.assertEqual(public["world_precommitment_sha256"],
                             result["world_precommitment_sha256"])
            self.assertEqual(result["public_receipt_file_sha256"],
                             sha_bytes(pub.read_bytes()))
            self.assertEqual(stat.S_IMODE(priv.stat().st_mode),0o700)
            self.assertEqual(stat.S_IMODE((priv/"private-envelope.json").stat().st_mode),0o600)
            self.assertEqual(stat.S_IMODE(pub.stat().st_mode),0o600)

    def test_existing_paths_never_overwritten_or_resealed(self):
        with tempfile.TemporaryDirectory() as tmp:
            base=Path(tmp)
            cfg=base/"config.json"
            cfg.write_text(json.dumps(invented()))
            priv=base/"vault"
            pub=base/"receipt.json"
            seal_offline(cfg,priv,pub,nonce=b"\x06"*32)
            original_pub=pub.read_bytes()
            with self.assertRaisesRegex(G5Blocked,"OUTPUT_ALREADY_EXISTS"):
                seal_offline(cfg,priv,pub,nonce=b"\x07"*32)
            self.assertEqual(pub.read_bytes(),original_pub)

    def test_paths_inside_repo_rejected_even_if_ignored(self):
        with tempfile.TemporaryDirectory() as tmp:
            base=Path(tmp)
            cfg=base/"config.json"
            cfg.write_text(json.dumps(invented()))
            with self.assertRaisesRegex(G5Blocked,"PATH_INSIDE_REPO"):
                seal_offline(ROOT/"experiments/cafeteria/pc01/private/config.json",
                             base/"vault",base/"receipt.json")
            with self.assertRaisesRegex(G5Blocked,"PATH_INSIDE_REPO"):
                seal_offline(cfg,ROOT/"experiments/cafeteria/pc01/private",
                             base/"receipt.json")
            with self.assertRaisesRegex(G5Blocked,"PATH_INSIDE_REPO"):
                seal_offline(cfg,base/"vault",
                             ROOT/"experiments/cafeteria/pc01/receipt.json")

    def test_same_public_parent_and_private_folder_not_confused(self):
        with tempfile.TemporaryDirectory() as tmp:
            base=Path(tmp)
            cfg=base/"config.json"
            cfg.write_text(json.dumps(invented()))
            with self.assertRaisesRegex(G5Blocked,"PATHS_NOT_SEPARATE"):
                seal_offline(cfg,base/"vault",
                             base/"vault/receipt.json",nonce=b"\x06"*32)

    def test_private_config_rejects_unknown_fields_no_silent_truth_change(self):
        cfg=invented()
        cfg["mechanism"]="not authorized"
        with self.assertRaisesRegex(G5Blocked,"INVALID_PRIVATE_CONFIG"):
            self.receipt(cfg)

    def test_execution_is_not_implicitly_authorized_by_matching_hashes(self):
        r=self.receipt()
        proof=verify_receipt(invented(),b"\x05"*32,r,
                             pinned_files=snapshot_files(),
                             budget=hard_budget(self.contract))
        self.assertFalse(proof["external_custody_verified"])
        self.assertFalse(proof["execution_authorized"])
        self.assertEqual(proof["state"],
                         "LOCAL_RECOMPUTATION_MATCHES_NOT_EXTERNALLY_WITNESSED")


if __name__ == "__main__":
    unittest.main()
